export const LOCALES = { 'zh-TW': zhTW, en, 'zh-CN': zhCN, ja };

// 佔位符抽取（{name} 形式）——不用 regex，方便 panel 端同一份邏輯（template literal 禁 regex）
export function placeholdersOf(s) {
  const out = [];
  const str = String(s ?? '');
  let i = 0;
  for (;;) {
    const a = str.indexOf('{', i);
    if (a === -1) break;
    const b = str.indexOf('}', a + 1);
    if (b === -1) break;
    const name = str.slice(a + 1, b);
    if (name && !name.includes(' ') && !out.includes(name)) out.push(name);
    i = b + 1;
  }
  return out.sort();
}

/**
 * 查字典並替換佔位符。缺 key → 退 zh-TW → 回 key 本身（永不拋錯，UI 不能因翻譯缺漏掛掉）。
 * 佔位符替換一次成型：值裡若含 {x} 不會被二次替換。
 */
export function t(locale, key, params) {
  const dict = LOCALES[locale] ?? LOCALES[DEFAULT_LOCALE];
  const tpl = dict[key] ?? LOCALES[DEFAULT_LOCALE][key] ?? key;
  if (!params) return tpl;
  let out = '';
  let i = 0;
  for (;;) {
    const a = tpl.indexOf('{', i);
    if (a === -1) { out += tpl.slice(i); break; }
    const b = tpl.indexOf('}', a + 1);
    if (b === -1) { out += tpl.slice(i); break; }
    const name = tpl.slice(a + 1, b);
    if (Object.prototype.hasOwnProperty.call(params, name)) {
      out += tpl.slice(i, a) + String(params[name] ?? '');
    } else {
      out += tpl.slice(i, b + 1);
    }
    i = b + 1;
  }
  return out;
}

// 偏好（'auto' / 語系 id / 空）+ 系統語言（BCP47 或 POSIX）→ 我們有的語系 id
export function resolveLocale(pref, systemLang) {
  const p = String(pref ?? '').trim();
  const direct = Object.keys(LOCALES).find((id) => id.toLowerCase() === p.toLowerCase());
  if (direct) return direct;
  const sys = String(systemLang ?? '').trim().replace(/_/g, '-').toLowerCase();
  if (!sys) return FALLBACK_LOCALE;
  const parts = sys.split('-');
  const lang = parts[0];
  if (lang === 'zh') {
    // 繁體：zh-TW / zh-HK / zh-MO / zh-Hant-*；其餘（zh、zh-CN、zh-SG、zh-Hans-*）視為簡體
    const traditional = parts.includes('hant') || parts.includes('tw') || parts.includes('hk') || parts.includes('mo');
    return traditional ? 'zh-TW' : 'zh-CN';
  }
  if (lang === 'ja') return 'ja';
  if (lang === 'en') return 'en';
  return FALLBACK_LOCALE;
}

// worker 端系統語言：POSIX 環境變數優先（LC_ALL > LC_MESSAGES > LANG；'C'/'POSIX' 不算），
// 都沒有才看 Intl（GUI fork 的 worker 常常沒有 LANG）。回 BCP47 樣式字串或空字串。
export function detectSystemLocale({ env = process.env, intlLocale } = {}) {
  for (const k of ['LC_ALL', 'LC_MESSAGES', 'LANG']) {
    const v = String(env?.[k] ?? '').trim();
    if (!v) continue;
    const base = v.split('.')[0].split('@')[0];
    if (!base || base === 'C' || base === 'POSIX') continue;
    return base.replace(/_/g, '-');
  }
  if (intlLocale !== undefined) return String(intlLocale ?? '');
  try { return String(Intl.DateTimeFormat().resolvedOptions().locale ?? ''); } catch { return ''; }
}

// 內嵌進 panel / dashboard 的整包（JSON 可序列化）
export function localePack() {
  return { locales: LOCALES, names: LOCALE_NAMES, default: DEFAULT_LOCALE, fallback: FALLBACK_LOCALE };
}
